// Renders the five pass images and writes the source of the generated module
// src/apple/artwork.ts. The module is produced once by scripts/make-artwork.ts and
// committed, so the images ship inside the Lambda bundles with no loader and no file read.
// Image sizes follow Apple's Wallet design guidance: icon 29 points, logo up to 160 by 50
// points, at 1x, 2x and 3x (the live Apple page could not be fetched while building, so the
// sizes come from the published guidance as recorded in the design).
import { drawIcon, drawLogo } from './draw.js';
import { encodePng } from './png.js';

export const ARTWORK_FILES = [
  'icon.png',
  'icon@2x.png',
  'icon@3x.png',
  'logo@2x.png',
  'logo@3x.png',
] as const;

export type ArtworkName = (typeof ARTWORK_FILES)[number];

export function renderArtwork(): Record<ArtworkName, Uint8Array> {
  const icon = (size: number) => {
    const raster = drawIcon(size);
    return encodePng(raster.width, raster.height, raster.rgba);
  };
  const logo = (width: number, height: number) => {
    const raster = drawLogo(width, height);
    return encodePng(raster.width, raster.height, raster.rgba);
  };
  return {
    'icon.png': icon(29),
    'icon@2x.png': icon(58),
    'icon@3x.png': icon(87),
    'logo@2x.png': logo(320, 100),
    'logo@3x.png': logo(480, 150),
  };
}

/** The TypeScript source of src/apple/artwork.ts for the given images. */
export function artworkModuleSource(files: Record<ArtworkName, Uint8Array>): string {
  const entries = ARTWORK_FILES.map(
    (name) => `  '${name}': '${Buffer.from(files[name]).toString('base64')}',`,
  );
  return [
    '// Generated by packages/pass-service/scripts/make-artwork.ts. Do not edit by hand.',
    '// Original artwork: a compass rose and a "Compass" wordmark, in an original palette.',
    'export const ARTWORK: Readonly<Record<string, string>> = {',
    ...entries,
    '};',
    '',
  ].join('\n');
}
