// The pass image file list and the writer of the generated module src/apple/artwork.ts.
// The images are the owner's artwork (site/public/artwork/logo.svg and favicon.svg), rendered
// by scripts/make-artwork.mjs (task 38). The module is committed, so the images ship inside the
// Lambda bundles with no loader and no file read. Image sizes follow Apple's Wallet Human Interface
// Guidelines: icon 38 points, logo up to 160 by 50 points, at 1x, 2x and 3x.

export const ARTWORK_FILES = [
  'icon.png',
  'icon@2x.png',
  'icon@3x.png',
  'logo.png',
  'logo@2x.png',
  'logo@3x.png',
] as const;

export type ArtworkName = (typeof ARTWORK_FILES)[number];

/** The TypeScript source of src/apple/artwork.ts for the given images. */
export function artworkModuleSource(files: Record<ArtworkName, Uint8Array>): string {
  const entries = ARTWORK_FILES.map(
    // Key and value on separate lines, as Prettier formats a long string value.
    (name) => `  '${name}':\n    '${Buffer.from(files[name]).toString('base64')}',`,
  );
  return [
    '// Generated by packages/pass-service/scripts/make-artwork.mjs. Do not edit by hand.',
    "// The owner's artwork: site/public/artwork/logo.svg and site/public/artwork/favicon.svg.",
    'export const ARTWORK: Readonly<Record<string, string>> = {',
    ...entries,
    '};',
    '',
  ].join('\n');
}
