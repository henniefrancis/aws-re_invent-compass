// The pass image file list and the writer of the generated module src/apple/artwork.ts.
// The images are the owner's artwork (site/public/artwork/logo.svg, favicon.svg and
// pass-background.png), rendered by scripts/make-artwork.mjs (tasks 38 and 44). The module is
// committed, so the images ship inside the Lambda bundles with no loader and no file read. Image
// sizes follow Apple's Wallet Human Interface Guidelines: icon 38 points and logo up to 160 by 50
// points at 1x, 2x and 3x; the event ticket background 343 by 503 points at 1x only: the owner's
// Pass Designer gradient weighs 538 KB at 2x, and Wallet blurs an event ticket background, so
// the 1x image looks the same and a 10-pass bundle stays under Lambda's 6 MB response limit.

export const ARTWORK_FILES = [
  'icon.png',
  'icon@2x.png',
  'icon@3x.png',
  'logo.png',
  'logo@2x.png',
  'logo@3x.png',
  'background.png',
] as const;

/** The most the whole artwork set may weigh, in bytes (tasks 42 and 44). */
export const ARTWORK_BUDGET_BYTES = 420 * 1024;

export type ArtworkName = (typeof ARTWORK_FILES)[number];

/** The TypeScript source of src/apple/artwork.ts for the given images. */
export function artworkModuleSource(files: Record<ArtworkName, Uint8Array>): string {
  const entries = ARTWORK_FILES.map(
    // Key and value on separate lines, as Prettier formats a long string value.
    (name) => `  '${name}':\n    '${Buffer.from(files[name]).toString('base64')}',`,
  );
  return [
    '// Generated by packages/pass-service/scripts/make-artwork.mjs. Do not edit by hand.',
    "// The owner's artwork: site/public/artwork/logo.svg, favicon.svg and pass-background.png.",
    'export const ARTWORK: Readonly<Record<string, string>> = {',
    ...entries,
    '};',
    '',
  ].join('\n');
}
