// Writes src/adapters/qr-brand.ts from the owner's artwork (compass-power task 49). Run once after
// the site's logo or icon changes, then commit the generated module:
//   node packages/mcp-server/scripts/make-qr-brand.mjs
//
// The QR page's Content-Security-Policy allows images only as data: URLs, and the npm package
// cannot read the site folder at run time, so the two SVGs travel inside the package as base64.
import { readFileSync, writeFileSync } from 'node:fs';

const artwork = new URL('../../../site/public/artwork/', import.meta.url);
const base64 = (name) => readFileSync(new URL(name, artwork)).toString('base64');

const source = [
  '// Generated by packages/mcp-server/scripts/make-qr-brand.mjs. Do not edit by hand.',
  "// The owner's artwork: site/public/artwork/logo.svg and favicon.svg (task 49).",
  '',
  '/** The full logo, as base64 SVG. */',
  'export const QR_BRAND_LOGO =',
  `  '${base64('logo.svg')}';`,
  '',
  '/** The icon, as base64 SVG. */',
  'export const QR_BRAND_ICON =',
  `  '${base64('favicon.svg')}';`,
  '',
].join('\n');

writeFileSync(new URL('../src/adapters/qr-brand.ts', import.meta.url), source);
console.log('wrote src/adapters/qr-brand.ts');
